#!/usr/bin/env node
/**
 * Generate `npm/wasm32/lib/wasm-inline.js` from `npm/wasm32/lib/embedpdf.wasm`:
 * the binary, gzipped, as a base64 string in an ES module.
 *
 * This is the PORTABLE delivery of the wasm — through the module graph, the
 * one channel every bundler understands (`@embedpdf/engine/portable` imports
 * it lazily). Gzip first so the module costs the same over the wire as the
 * file it stands in for (~2.7 MB) instead of a third more; the browser
 * inflates it with `DecompressionStream`. Generated from the same binary the
 * package ships, in the same build step, so the two can never disagree.
 * Skipped (not failed) when the wasm payload is not staged yet.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const lib = resolve(root, 'npm', 'wasm32', 'lib');
const wasm = resolve(lib, 'embedpdf.wasm');
if (!existsSync(wasm)) {
  console.log('generate-wasm-inline: npm/wasm32/lib/embedpdf.wasm not staged; skipping');
  process.exit(0);
}
const packed = gzipSync(readFileSync(wasm), { level: 9 });
const source =
  `// Generated by build/generate-wasm-inline.mjs — lib/embedpdf.wasm, gzip, base64. Do not edit.\n` +
  `export default '${packed.toString('base64')}';\n`;
writeFileSync(resolve(lib, 'wasm-inline.js'), source);
console.log(`generate-wasm-inline: ${Math.round(source.length / 1024)} kB module written`);
