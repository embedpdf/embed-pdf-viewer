#!/usr/bin/env node
/**
 * How each character of a cursive script joins its neighbours, as the
 * engine's shaper reads it: generated from the fork's HarfBuzz
 * (`hb-ot-shaper-arabic-table.hh`, itself generated from Unicode's
 * ArabicShaping.txt), so the painter joins letters exactly where the engine
 * does.
 *
 * Writes `src/joining.generated.ts`: each listed character's type as ranges.
 * Syriac's Alaph and Dalath-Rish groups join as right-joining letters do; a
 * character the table leaves out (HarfBuzz's `X`) is left out here too, and
 * `joiningTypeOf` gives it the type HarfBuzz does from its general category.
 *
 * Run it after the fork's HarfBuzz changes:
 *   node packages/core/text/scripts/generate-joining-types.mjs
 * `--check` compares instead of writing (the test runs it).
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const TABLE = resolve(
  HERE,
  '../../../engine/runtime/runtime-src/third_party/harfbuzz-ng/src/src/hb-ot-shaper-arabic-table.hh',
);
const OUT = resolve(HERE, '../src/joining.generated.ts');
const TYPES = { U: 'U', L: 'L', R: 'R', D: 'D', C: 'C', T: 'T', A: 'R', DR: 'R' };

const source = readFileSync(TABLE, 'utf8');
const table = source.slice(source.indexOf('joining_table[]'), source.indexOf('};'));
const version = /# (ArabicShaping-[\d.]+)\.txt/.exec(source)?.[1] ?? 'ArabicShaping';

// The table as HarfBuzz reads it: its values in order, and each block's code points, from
// `joining_type()`, at the block's offset into them (a block's first row is padded to the column
// its first code point would have, so a row's label isn't where its values start).
const values = table
  .replace(/\/\*[^]*?\*\//g, '')
  .replace(/#define[^\n]*/g, '')
  .slice(table.indexOf('{') + 1)
  .split(',')
  .map((value) => value.trim())
  .filter(Boolean);
const offsets = new Map(
  [...source.matchAll(/#define joining_offset_0x([0-9a-f]+)u (\d+)/g)].map(([, start, offset]) => [
    parseInt(start, 16),
    Number(offset),
  ]),
);
const types = new Map();
for (const [, first, last] of source.matchAll(
  /hb_in_range<hb_codepoint_t> \(u, 0x([0-9A-F]+)u, 0x([0-9A-F]+)u\)\) return joining_table/g,
)) {
  const start = parseInt(first, 16);
  const offset = offsets.get(start);
  for (let codePoint = start; codePoint <= parseInt(last, 16); codePoint += 1) {
    const value = values[codePoint - start + offset];
    if (value !== 'X') types.set(codePoint, TYPES[value]);
  }
}

const ranges = [];
for (const codePoint of [...types.keys()].sort((a, b) => a - b)) {
  const type = types.get(codePoint);
  const last = ranges[ranges.length - 1];
  if (last && last[1] === codePoint - 1 && last[2] === type) last[1] = codePoint;
  else ranges.push([codePoint, codePoint, type]);
}

const hash = createHash('sha256').update(source).digest('hex');
const text = `// Generated by packages/core/text/scripts/generate-joining-types.mjs from the fork's HarfBuzz (${version}). Don't edit.

/** The SHA-256 of HarfBuzz's table these were generated from. */
export const SOURCE_HASH = '${hash}';

/** Each listed character's joining type, as ranges in order: \`[first, last, type]\`. */
export const JOINING_TYPES: readonly (readonly [number, number, 'U' | 'L' | 'R' | 'D' | 'C' | 'T'])[] = [
${ranges.map(([first, last, type]) => `  [0x${first.toString(16)}, 0x${last.toString(16)}, '${type}'],`).join('\n')}
];
`;

if (process.argv.includes('--check')) {
  if (readFileSync(OUT, 'utf8') !== text) {
    console.error(`${OUT} is not what HarfBuzz's table gives: run the generator.`);
    process.exit(1);
  }
} else {
  writeFileSync(OUT, text);
  console.log(`${ranges.length} ranges from ${types.size} characters (${version})`);
}
