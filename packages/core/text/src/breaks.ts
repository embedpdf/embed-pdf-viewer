/**
 * Where a line may break, as the engine decides it: a port of PDFium's
 * character classes (`cpvt_section.cpp`), quirks included (every character
 * from U+0080 to U+0094 counts as punctuation).
 */

/** Per ASCII character: 0x01 Latin letter, 0x02 digit, 0x04 opening, 0x08 punctuation, 0x20 connective. */
