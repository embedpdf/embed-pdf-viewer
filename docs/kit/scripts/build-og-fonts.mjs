#!/usr/bin/env node
/**
 * Regenerates src/og/fonts.data.ts from the `@fontsource/*` devDependencies.
 *
 *   node scripts/build-og-fonts.mjs
 *
 * The faces are inlined as base64 rather than read from disk at render time
 * because every path-based approach breaks under bundling: `require.resolve`
 * gets rewritten to webpack's resolver and cannot find a non-module file, and
 * `new URL(..., import.meta.url)` is rewritten to a root-relative asset path
 * that no `fetch` can take during static generation. A string constant has
 * nothing left to resolve, and behaves the same under webpack, Turbopack,
 * Node and Edge.
 *
 * Only latin `.woff` — Satori cannot read woff2 (no brotli decoder), and the
 * cards are latin-only text.
 */
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const here = path.dirname(fileURLToPath(import.meta.url));

const FACES = [
  ['MANROPE_800', '@fontsource/manrope/files/manrope-latin-800-normal.woff'],
  ['MANROPE_700', '@fontsource/manrope/files/manrope-latin-700-normal.woff'],
  ['INTER_400', '@fontsource/inter/files/inter-latin-400-normal.woff'],
  ['JETBRAINS_MONO_400', '@fontsource/jetbrains-mono/files/jetbrains-mono-latin-400-normal.woff'],
];

const lines = [
  '/**',
  ' * GENERATED by scripts/build-og-fonts.mjs — do not edit.',
  ' *',
  ' * Latin `.woff` faces, base64-encoded. See ./fonts.ts for why they are',
  ' * inlined rather than read from disk, and ./fonts/ for the upstream',
  ' * licences.',
  ' */',
  '',
];

for (const [name, specifier] of FACES) {
  const bytes = fs.readFileSync(require.resolve(specifier));
  lines.push(`/** ${specifier} */`);
  lines.push(`export const ${name} = '${bytes.toString('base64')}';`);
  lines.push('');
}

const out = path.join(here, '..', 'src', 'og', 'fonts.data.ts');
fs.writeFileSync(out, lines.join('\n'));
console.log(
  `wrote ${path.relative(process.cwd(), out)} (${(fs.statSync(out).size / 1024).toFixed(0)}KB)`,
);
